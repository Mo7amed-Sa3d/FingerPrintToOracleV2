CREATE TABLE device_machines (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    IP          VARCHAR2(45) NOT NULL,
    PORT        NUMBER(5) DEFAULT 4370 NOT NULL,
    STATUS      VARCHAR2(20),
    STATUS_TIME TIMESTAMP,

    CONSTRAINT pk_device_machines
        PRIMARY KEY (ID),

    CONSTRAINT uq_device_machines_ip_port
        UNIQUE (IP, PORT)
);

CREATE TABLE checkinout (
    ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USERID     VARCHAR2(50) NOT NULL,
    CHECKTIME  TIMESTAMP NOT NULL,
    CHECKTYPE  CHAR(1) NOT NULL,
    VERIFYCODE NUMBER,
    DEVICEID   NUMBER NOT NULL,

    CONSTRAINT pk_checkinout
        PRIMARY KEY (ID),

    CONSTRAINT fk_checkinout_device
        FOREIGN KEY (DEVICEID)
        REFERENCES device_machines(ID),

    CONSTRAINT ck_checkinout_type
        CHECK (CHECKTYPE IN ('I', 'O')),

    CONSTRAINT uq_checkinout_punch
        UNIQUE (USERID, CHECKTIME, DEVICEID)
);

CREATE INDEX idx_checkinout_user
    ON checkinout (USERID);

CREATE INDEX idx_checkinout_time
    ON checkinout (CHECKTIME);

CREATE INDEX idx_checkinout_device
    ON checkinout (DEVICEID);

CREATE INDEX idx_checkinout_user_time
    ON checkinout (USERID, CHECKTIME);